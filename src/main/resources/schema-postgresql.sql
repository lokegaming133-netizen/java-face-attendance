-- Cloud PostgreSQL schema; safe to re-run on app startup.
-- Existing H2 file remains untouched on the local laptop.
CREATE TABLE IF NOT EXISTS students (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    roll VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    gender VARCHAR(40) NOT NULL DEFAULT 'Not specified'
);
CREATE TABLE IF NOT EXISTS samples (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student INTEGER NOT NULL REFERENCES students(id),
    image BYTEA NOT NULL
);
CREATE TABLE IF NOT EXISTS attendance (
    student INTEGER NOT NULL REFERENCES students(id),
    session_name VARCHAR(100) NOT NULL,
    marked_at VARCHAR(40) NOT NULL,
    method VARCHAR(20) NOT NULL,
    PRIMARY KEY (student, session_name)
);
CREATE TABLE IF NOT EXISTS face_embeddings (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student INTEGER NOT NULL REFERENCES students(id),
    embedding BYTEA NOT NULL
);
